def _npy_bytes(arr: np.ndarray) -> bytes:
    buf = io.BytesIO()
    np.save(buf, arr, allow_pickle=False)
    return buf.getvalue()


def _member_bytes(name: str, data: bytes) -> bytes:
    ti = tarfile.TarInfo(name)
    ti.size = len(data)
    ti.mtime = 0
    ti.mode = 0o644
    try:
        hdr = ti.tobuf(tarfile.USTAR_FORMAT)
    except ValueError:  # name too long for ustar
        hdr = ti.tobuf(tarfile.GNU_FORMAT)
    pad = (512 - len(data) % 512) % 512
    return hdr + data + b"\0" * pad


def _scan_tar(raw: bytes):
    """-> (frame keys sorted, lowdim (T,116) f32, presence (T,) uint8, end offset)."""
    lowdims, presence, jpgs = {}, {}, []
    end = 0
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:") as tf:
        for m in tf:
            if not m.isfile():
                continue
            end = max(end, m.offset_data + ((m.size + 511) // 512) * 512)
            if m.name.endswith(".image.jpg"):
                jpgs.append(m.name)
            elif m.name.endswith(".lowdim.npy"):
                lowdims[m.name[: -len(".lowdim.npy")]] = np.load(
                    io.BytesIO(tf.extractfile(m).read()), allow_pickle=False)
            elif m.name.endswith(".meta.json"):
                presence[m.name[: -len(".meta.json")]] = int(
                    json.loads(tf.extractfile(m).read())["presence"])
            elif m.name.endswith(GT_SUFFIX):
                raise ValueError(f"tar already carries {m.name}")
    keys = sorted(n[: -len(".image.jpg")] for n in jpgs)
    if sorted(lowdims) != keys or sorted(presence) != keys:
        raise ValueError("jpg/lowdim/meta member mismatch")
    if raw[end:].lstrip(b"\0"):
        raise ValueError("non-zero bytes after last member (unexpected trailer)")
    ld = np.stack([lowdims[k] for k in keys]).astype(np.float32)
    pres = np.array([presence[k] for k in keys], np.uint8)
    return keys, ld, pres, end


def expected_new_size(old_size: int, old_end: int, n_frames: int) -> int:
    body = old_end + n_frames * PER_FRAME_APPEND
    return ((body + 1024 + RECORDSIZE - 1) // RECORDSIZE) * RECORDSIZE


# ------------------------------------------------------------------ source loaders

def _episode_joints_zarr3(stem: str):
    """(lk, rk (Tep,21,3) f64, vl, vr (Tep,) bool, C0 (3,) f64) from the source zarr,
    following EgoverseZarr3Extractor.load + the recenter_world chain exactly."""
    from generate_keypoints_wds import read_zarr3_array, _quat_to_rotmat, _invert_se3
    src = _CFG["src"].replace("gs://", "")
    with tempfile.TemporaryDirectory(prefix="egv_") as td:
        work = Path(td)
        for a in ("left.obs_keypoints", "right.obs_keypoints", "obs_head_pose"):
            _FS.get(f"{src}/{stem}.zarr/{a}/", str(work / a) + "/", recursive=True)
        lk = read_zarr3_array(work / "left.obs_keypoints").reshape(-1, 21, 3)
        rk = read_zarr3_array(work / "right.obs_keypoints").reshape(-1, 21, 3)
        head = read_zarr3_array(work / "obs_head_pose")
    c2w = np.tile(np.eye(4), (1, 1, 1))
    c2w[:, :3, :3] = _quat_to_rotmat(head[:1, 3:7], "wxyz")
    c2w[:, :3, 3] = head[0, :3]
    w2c0 = _invert_se3(c2w)[0]
    C0 = -(w2c0[:3, :3].T @ w2c0[:3, 3])
    vl = np.abs(lk).sum(axis=(1, 2)) > 1e-8
    vr = np.abs(rk).sum(axis=(1, 2)) > 1e-8
    return lk, rk, vl, vr, C0


def _episode_joints_posejson(stem: str):
    """Same contract from lightwheel pose.json + camera params (for the C0 candidate)."""
    from generate_keypoints_wds import LightwheelPoseJsonExtractor
    src = _CFG["src"].replace("gs://", "")
    cam = _CFG["camera"]
    pose = json.loads(_FS.cat(f"{src}/{stem}/pose.json"))
    prm = json.loads(_FS.cat(f"{src}/{stem}/{cam}/{cam}_params.json"))
    pf, cf = pose["frames"], prm["frames"]
    Tep = min(len(pf), len(cf))
    lk, _lq, vl = LightwheelPoseJsonExtractor._hand_arrays(pf[:Tep], "left_hand", TIPS)
    rk, _rq, vr = LightwheelPoseJsonExtractor._hand_arrays(pf[:Tep], "right_hand", TIPS)
    R0 = np.array(cf[0]["R_w2c"], np.float64)
    t0 = np.array(cf[0]["t_w2c"], np.float64)
    C0 = -(R0.T @ t0)
    return lk, rk, vl, vr, C0


def _stream_retry(fn, attempts=3):
    err = None
    for a in range(attempts):
        try:
            return fn()
        except Exception as e:  # noqa: BLE001
            err = e
            time.sleep(5 * (a + 1))
    raise RuntimeError(f"{type(err).__name__}: {err}")


# ------------------------------------------------------------------ retrofit worker

def retrofit_episode(job):
    """job = (stem, clips=[{clip_id, rel, seg:[s,e]}]). One result dict per clip."""
    stem, clips = job
    results = []
    try:
        loader = (_episode_joints_zarr3 if _CFG["kind"] == "zarr3"
                  else _episode_joints_posejson)
        lk, rk, vl, vr, C0 = _stream_retry(lambda: loader(stem))
    except Exception as e:  # noqa: BLE001
        return [dict(clip_id=c["clip_id"], ok=False,
                     error=f"episode: {type(e).__name__}: {e}") for c in clips]
    # both world-frame candidates, full episode, float32 (untracked rows stay zero)
    cands = {}
    for mode, off in (("raw", None), ("recentered", C0)):
        L = lk if off is None else np.where(vl[:, None, None], lk - off, lk)
        R = rk if off is None else np.where(vr[:, None, None], rk - off, rk)
        cands[mode] = np.stack([L, R], axis=1).astype(np.float32)  # (Tep,2,21,3)
    tol = float(_CFG["tol"])
    dst_root = _CFG["dst_prefix"].replace("gs://", "")
    for c in clips:
        t0 = time.time()
        out = dict(clip_id=c["clip_id"])
        try:
            raw = _stream_retry(lambda: _FS.cat(c["src_tar"].replace("gs://", "")))
            keys, ld, pres, end = _scan_tar(raw)
            T = len(keys)
            s, e = c["seg"]
            if e - s != T:
                raise ValueError(f"segment_frame_range {c['seg']} != tar frames {T}")
            if e > lk.shape[0]:
                raise ValueError(f"segment end {e} > episode frames {lk.shape[0]}")
            # validate both candidates on presence-on frame+hand; ship the exact one
            best_mode, best_err, n_checked, gt = None, None, 0, None
            for mode, cand in cands.items():
                g = cand[s:e]
                errs, nchk = [], 0
                for hb, (wsl, tsl) in enumerate(((LD_LWRIST, LD_LTIPS),
                                                 (LD_RWRIST, LD_RTIPS))):
                    on = (pres & (1 << hb)) > 0
                    if not on.any():
                        continue
                    nchk += int(on.sum())
                    errs.append(np.abs(ld[on, wsl] - g[on, hb, 0]).max())
                    errs.append(np.abs(ld[on, tsl].reshape(-1, 5, 3)
                                       - g[on, hb][:, TIPS]).max())
                if nchk == 0:
                    raise ValueError("no presence-on frames to validate against")
                err = float(max(errs))
                if err <= tol and (best_err is None or err < best_err):
                    best_mode, best_err, n_checked, gt = mode, err, nchk, g
            if best_mode is None:
                raise ValueError("lowdim/recompute mismatch in BOTH world modes "
                                 f"(> {tol})")
            if not np.isfinite(gt).all():
                raise ValueError("non-finite recomputed GT joints")
            parts = [raw[:end]]
            parts += [_member_bytes(k + GT_SUFFIX, _npy_bytes(gt[t]))
                      for t, k in enumerate(keys)]
            body = sum(len(p) for p in parts)
            total = ((body + 1024 + RECORDSIZE - 1) // RECORDSIZE) * RECORDSIZE
            parts.append(b"\0" * (total - body))
            blob = b"".join(parts)
            assert len(blob) == expected_new_size(len(raw), end, T), "size-model drift"
            _stream_retry(lambda: _FS.pipe(f"{dst_root}/{c['rel']}", blob))
            out.update(ok=True, frames=T, checked=n_checked, max_err=best_err,
                       mode=best_mode, old_size=len(raw), new_size=len(blob))
        except Exception as e:  # noqa: BLE001
            out.update(ok=False, error=f"{type(e).__name__}: {e}")
        out["sec"] = round(time.time() - t0, 3)
        results.append(out)
    return results


# ------------------------------------------------------------------ index mode

def _parse_shard(shard_path):
    """One _shards/*.filtered.jsonl -> compact rows for the jobs index."""
    rows = []
    with _FS.open(shard_path, "rb") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            d = r["descriptor"]
            ex = d["extra"]
            sp = d["shard_path"]
            m = re.search(r"/frames/(shard_\d+/[^/]+\.tar)$", sp)
            if not m:
                raise ValueError(f"unexpected shard_path {sp}")
            rows.append(dict(clip_id=r["clip_id"], rel=m.group(1), src_tar=sp,
                             seg=ex["segment_frame_range"],
                             session_id=ex["session_id"]))
    return rows


def run_index(a, cfg):
    idx_path = Path(a.workdir) / "index.jsonl"
    idx_path.parent.mkdir(parents=True, exist_ok=True)
    import gcsfs
    fs = gcsfs.GCSFileSystem()
    shards = sorted(p for p in fs.ls(f"{a.manifest_dir}/_shards".replace("gs://", ""))
                    if p.endswith(".filtered.jsonl"))
    print(f"[index] {len(shards)} shard manifests", flush=True)
    ctx = __import__("multiprocessing").get_context("spawn")
    n = 0
    with ctx.Pool(min(a.workers, 32), initializer=_init, initargs=({},)) as pool, \
            open(idx_path, "w") as out:
        for i, rows in enumerate(pool.imap(_parse_shard, shards), 1):
            for row in rows:
                out.write(json.dumps(row) + "\n")
            n += len(rows)
            print(f"  shard {i}/{len(shards)} rows={n}", flush=True)
    print(f"[index] {n} clips -> {idx_path}")
    if cfg["expected_clips"] and n != cfg["expected_clips"]:
        print(f"[index] WARNING: expected {cfg['expected_clips']} clips, got {n}")
        return 1
    return 0


def _load_index(a):
    rows = [json.loads(l) for l in open(Path(a.workdir) / "index.jsonl")
            if l.strip()]
    return rows


# ------------------------------------------------------------------ retrofit driver

def run_retrofit(a, cfg):
    import gcsfs
    fs = gcsfs.GCSFileSystem()
    rows = _load_index(a)
    if a.include:
        rows = [r for r in rows if re.search(a.include, r["clip_id"])]
    if a.limit:
        rows = rows[: a.limit]
    strip = cfg["strip"]
    by_ep = {}
    for r in rows:
        sid = r["session_id"]
        if not sid.startswith(strip):
            raise ValueError(f"session_id {sid} does not start with {strip}")
        by_ep.setdefault(sid[len(strip):], []).append(r)
    done = set()
    if a.resume:
        try:
            done = {p.split("/frames_v2/", 1)[1] for p in
                    fs.find(a.dst_prefix.replace("gs://", ""))}
        except FileNotFoundError:
            done = set()
        print(f"[resume] {len(done)} objects already at {a.dst_prefix}", flush=True)
    jobs = []
    for stem, clips in sorted(by_ep.items()):
        todo = [c for c in clips if c["rel"] not in done]
        if todo:
            jobs.append((stem, todo))
    n_clips = sum(len(j[1]) for j in jobs)
    print(f"[retrofit] {len(jobs)} episodes / {n_clips} clips -> {a.dst_prefix} "
          f"(workers={a.workers})", flush=True)
    if not jobs:
        print("[retrofit] nothing to do")
        return 0
    cfg_w = dict(kind=cfg["kind"], src=cfg["src"], camera=cfg.get("camera"),
                 dst_prefix=a.dst_prefix, tol=a.tol)
    results_n, fails_n, max_err, modes = 0, 0, 0.0, {}
    log = open(a.log_out, "a") if a.log_out else None
    t0 = time.time()
    fail_samples = []
    ctx = __import__("multiprocessing").get_context("spawn")
    with ctx.Pool(a.workers, initializer=_init, initargs=(cfg_w,)) as pool:
        for i, outs in enumerate(pool.imap_unordered(retrofit_episode, jobs,
                                                     chunksize=4), 1):
            for o in outs:
                results_n += 1
                if o.get("ok"):
                    max_err = max(max_err, o["max_err"])
                    modes[o["mode"]] = modes.get(o["mode"], 0) + 1
                else:
                    fails_n += 1
                    if len(fail_samples) < 40:
                        fail_samples.append(o)
                if log:
                    log.write(json.dumps(o) + "\n")
            if log and (i % 50 == 0 or i == len(jobs)):
                log.flush()
            if i % 200 == 0 or i == len(jobs):
                dt = time.time() - t0
                print(f"  ep {i}/{len(jobs)}  clips={results_n}/{n_clips}  "
                      f"fails={fails_n}  {results_n/max(dt,1e-9):.1f} clips/s  "
                      f"eta={(n_clips-results_n)/max(results_n/max(dt,1e-9),1e-9)/60:.0f} min",
                      flush=True)
    if log:
        log.close()
    print(f"[retrofit] done: {results_n - fails_n} ok, {fails_n} failed; "
          f"max_err={max_err:.3e}; modes={modes}")
    for f in fail_samples[:20]:
        print("  FAIL", f["clip_id"], f["error"])
    return 1 if fails_n else 0


# ------------------------------------------------------------------ flip mode

def _flip_line(line: bytes, dst_prefix: str, schema: str):
    r = json.loads(line)
    d = r["descriptor"]
    old_root = dst_prefix.rsplit("/", 1)[0] + "/frames"
    if not d["root_dir"].startswith(dst_prefix):
        m = re.match(re.escape(old_root) + r"/(shard_\d+)$", d["root_dir"].rstrip("/"))
        assert m, f"unexpected root_dir {d['root_dir']}"
        d["root_dir"] = f"{dst_prefix}/{m.group(1)}"
        mp = re.search(r"/frames/(shard_\d+/[^/]+\.tar)$", d["shard_path"])
        assert mp, f"unexpected shard_path {d['shard_path']}"
        d["shard_path"] = f"{dst_prefix}/{mp.group(1)}"
        d["extra"].update({"gt_joints": True, "gt_joints_schema": schema,
                           "mano_note": MANO_NOTE})
    return json.dumps(r) + "\n"


def _flip_shard(args):
    shard_path, backup_dir, dst_prefix, schema = args
    base = os.path.basename(shard_path)
    bkp = f"{backup_dir}/{base}".replace("gs://", "")
    if not _FS.exists(bkp):
        _FS.copy(shard_path, bkp)
    out = io.BytesIO()
    n = 0
    with _FS.open(bkp, "rb") as f:
        for line in f:
            if line.strip():
                out.write(_flip_line(line, dst_prefix, schema).encode())
                n += 1
    _FS.pipe(shard_path, out.getvalue())
    return base, n


def run_flip(a, cfg):
    import gcsfs
    fs = gcsfs.GCSFileSystem()
    md = a.manifest_dir.replace("gs://", "")
    backup_dir = f"{a.manifest_dir}/_pre21_backup"
    shards = sorted(p for p in fs.ls(f"{md}/_shards")
                    if p.endswith(".filtered.jsonl"))
    print(f"[flip] {len(shards)} shard manifests; backups -> {backup_dir}", flush=True)
    jobs = [(s, f"{backup_dir}/_shards", a.dst_prefix, cfg["schema"]) for s in shards]
    ctx = __import__("multiprocessing").get_context("spawn")
    total = 0
    with ctx.Pool(min(a.workers, 16), initializer=_init, initargs=({},)) as pool:
        for base, n in pool.imap_unordered(_flip_shard, jobs):
            total += n
            print(f"  flipped {base}: {n} records", flush=True)
    print(f"[flip] shards done: {total} records")
    if cfg["expected_clips"] and total != cfg["expected_clips"]:
        print(f"[flip] ABORT combined rebuild: {total} != expected {cfg['expected_clips']}")
        return 1
    # combined manifest: backup, then regenerate by concatenating flipped shards
    comb = f"{md}/clip_manifest.filtered.jsonl"
    bkp = f"{backup_dir}/clip_manifest.filtered.jsonl".replace("gs://", "")
    if not fs.exists(bkp):
        fs.copy(comb, bkp)
        print(f"[flip] combined backup -> {bkp}")
    else:
        print(f"[flip] combined backup already present: {bkp}")
    with fs.open(comb, "wb") as out:
        for s in shards:
            with fs.open(s, "rb") as f:
                while True:
                    chunk = f.read(64 * 1024 * 1024)
                    if not chunk:
                        break
                    out.write(chunk)
    print(f"[flip] combined regenerated from {len(shards)} flipped shards")
    return 0


