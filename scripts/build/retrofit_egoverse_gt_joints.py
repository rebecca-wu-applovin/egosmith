def run_audit(a, cfg):
    import gcsfs
    fs = gcsfs.GCSFileSystem()
    rows = _load_index(a)
    logged = {}
    for lp in (a.log_out or "").split(","):
        if lp and os.path.exists(lp):
            for line in open(lp):
                r = json.loads(line)
                if r.get("ok"):
                    logged[r["clip_id"]] = r["new_size"]
    objs = {p.split("/frames_v2/", 1)[1]: i["size"] for p, i in
            fs.find(a.dst_prefix.replace("gs://", ""), detail=True).items()}
    missing, badsize, unlogged = [], [], 0
    for r in rows:
        sz = objs.get(r["rel"])
        if sz is None:
            missing.append(r["rel"])
            continue
        want = logged.get(r["clip_id"])
        if want is None:
            unlogged += 1
        elif sz != want:
            badsize.append((r["rel"], sz, want))
    print(f"[audit] manifest clips={len(rows)} dst objects={len(objs)} "
          f"missing={len(missing)} badsize={len(badsize)} unlogged={unlogged}")
    for b in (missing + [x[0] for x in badsize])[:20]:
        print("  BAD", b)
    rng = random.Random(0)
    sample = rng.sample(rows, min(a.sample, len(rows)))
    bad = 0
    for r in sample:
        raw = fs.cat(f"{a.dst_prefix}/{r['rel']}".replace("gs://", ""))
        lds, gts, pres = {}, {}, {}
        njpg = 0
        with tarfile.open(fileobj=io.BytesIO(raw)) as tf:
            for m in tf:
                if m.name.endswith(".image.jpg"):
                    njpg += 1
                elif m.name.endswith(".lowdim.npy"):
                    lds[m.name[:-11]] = np.load(io.BytesIO(tf.extractfile(m).read()))
                elif m.name.endswith(GT_SUFFIX):
                    gts[m.name[:-len(GT_SUFFIX)]] = np.load(
                        io.BytesIO(tf.extractfile(m).read()), allow_pickle=False)
                elif m.name.endswith(".meta.json"):
                    pres[m.name[:-10]] = int(json.loads(tf.extractfile(m).read())["presence"])
        keys = sorted(lds)
        ok = (njpg == len(gts) == len(lds) and keys == sorted(gts)
              and all(gts[k].shape == (2, 21, 3) and np.isfinite(gts[k]).all()
                      for k in keys))
        if ok:
            ld = np.stack([lds[k] for k in keys])
            gt = np.stack([gts[k] for k in keys])
            pr = np.array([pres[k] for k in keys])
            errs = [0.0]
            for hb, (wsl, tsl) in enumerate(((LD_LWRIST, LD_LTIPS),
                                             (LD_RWRIST, LD_RTIPS))):
                on = (pr & (1 << hb)) > 0
                if on.any():
                    errs.append(float(np.abs(ld[on, wsl] - gt[on, hb, 0]).max()))
                    errs.append(float(np.abs(ld[on, tsl].reshape(-1, 5, 3)
                                             - gt[on, hb][:, TIPS]).max()))
            ok = max(errs) <= a.tol
        if not ok:
            bad += 1
            print(f"  DEEP-BAD {r['rel']} njpg={njpg} ngt={len(gts)}")
    print(f"[audit] deep sample {len(sample)}: {len(sample)-bad} ok, {bad} bad")
    return 1 if (missing or badsize or bad) else 0


