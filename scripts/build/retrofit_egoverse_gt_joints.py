#!/usr/bin/env python
"""Retrofit the four shipped EgoVerse-native WDS tiers with full 21-joint GT
(.gt_joints.npy) — egoverse_lightwheel / egoverse_mecka_flagship / egoverse_scale /
egoverse_microagi.

The shipped tars carry {frame}.image.jpg/.lowdim.npy(116-d wrist+5tips)/.mano.npy
(zeros)/.meta.json; the source zarrs (and lightwheel pose.json) hold the full
21-joint world GT that generate_keypoints_wds.py read but never wrote (fixed
natively in commit "Emit full-skeleton gt_joints natively..."). This pass re-reads
each keeper episode's source joints — pose arrays only, no images — and APPENDS one
member per frame:

  {frame}.gt_joints.npy : (2, 21, 3) float32 world-frame joints, MANO/OpenPose order
                          (index 0 = left hand; wrist 0, tips 4/8/12/16/20 — the
                          layout the extractors + kpt audits verified). An all-zero
                          hand-frame = untracked sentinel; .meta.json presence stays
                          authoritative.
  schema tags: egoverse_world_21_mano_order_v1 (zarr tiers)
               lightwheel_world_21_mano_order_v1

WORLD-FRAME MODE (measured 2026-08-28): the shipped zarr tiers are recentered to the
first-frame camera centre (spec recenter_world), lightwheel is RAW source world —
the builds straddled the recenter_world spec change. The retrofit therefore
AUTO-DETECTS per clip: both candidates (raw / recentered via the exact converter
chain quat->c2w->invert->C0=-(R0^T t0)) are validated against the tar's own lowdim
wrist+tips on every PRESENCE-ON frame+hand, and only an exact (<= --tol, measured
0.0) match ships. Mismatch on both = failure, clip is NOT uploaded.

Append-at-end keeps every original member byte-identical at its original offset
(original archive = members + zero trailer; rewritten = members + new members + zero
trailer), so descriptor.frame_offsets stay valid and sequential native loaders skip
the unknown member name.

Outputs go to a NEW prefix (frames_v2/shard_XXXXX/) — v1 tars are never touched.
Modes:
  index     parse filter_run/_shards/*.filtered.jsonl in parallel into a compact
            local jobs index (clip_id, rel shard path, segment_frame_range,
            session_id). Validates the record count.
  retrofit  one job per EPISODE (source pose arrays streamed once): recompute the
            skeleton, validate + append + upload every clip of the episode.
            Resumable (skips clips whose dst object already exists).
  flip      rewrite the per-shard filtered manifests + the combined
            clip_manifest.filtered.jsonl -> frames_v2 pointers + extra flags
            (gt_joints/gt_joints_schema/mano_note), backing everything up to
            filter_run/_pre21_backup/ FIRST. The combined file is regenerated by
            concatenating the flipped shards in shard order (how it was gathered).
  audit     every manifest clip must have its frames_v2 tar at the retrofit-logged
            size + deep readback of a random sample (member counts, (2,21,3) shape,
            finiteness, in-tar gt-vs-lowdim exactness).

Fork-safety: gcsfs is not fork-safe -> spawn-context pools everywhere (the wiyh
retrofit lesson).
"""
